package com.example.demo.api.dto;

import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;

import java.util.List;
import java.util.Map;

/**
 * <p><b>schemaVersion</b></p> версия структуры анкеты. Не то, что вводит пользователь, а служебное поле для тебя: если через полгода поменяешь набор вопросов (добавишь/уберёшь поля), старые анкеты в БД останутся с прежним schemaVersion, а новые пойдут с новым — так можно отличить, по какой "версии вопросов" заполнялась конкретная запись, не ломая уже сохранённые данные. Обсуждали это в самом начале при проектировании Questionnaire таблицы.
 * <p><b>request</b></p> свободный текст: с чем пользователь пришёл, что его беспокоит или какой у него запрос к специалисту. Обязательное поле (@NotBlank), потому что без него специалисту физически не с чем начинать оценку.
 * <p><b>goals</b></p> список целей пользователя (например, "похудеть", "восстановление после травмы", "улучшить осанку"). @NotEmpty — хотя бы одна цель обязательна, @NotBlank на элементах списка — каждая отдельная цель в списке не может быть пустой строкой.
 * <p><b>wellbeing</b></p> самочувствие на момент заполнения анкеты (например, "нормальное", "болит поясница", "быстро устаю"). Не обязательное поле — без валидации, потому что не у всех есть что сообщить про самочувствие, и жёстко требовать текст тут избыточно.
 * <p><b>restrictions</b></p> ограничения: травмы, противопоказания, то, что нельзя делать (например, "нельзя нагружать колено", "аллергия на латекс" — если вдруг понадобится для каких-то тренажёров/оборудования). Тоже не обязательное — список может быть пустым, если ограничений нет.
 * <p><b>extra</b></p> "расширяемый хвост", который разбирали в самом начале проектирования Questionnaire. Сюда попадает всё, что ты ещё не выделил в отдельное явное поле, но что уже нужно собирать (например, если позже добавишь вопрос "как часто тренируешься" — можно сразу прокидывать через extra, не трогая DTO и не делая миграцию БД, а когда поле "стабилизируется" — вынести его в явный параметр записи).
 */
public record QuestionnaireCreateDto(
        @Min(value = 1, message = "Некорректная версия схемы")
        int schemaVersion,

        @NotBlank(message = "Опишите ваш запрос")
        String request,

        @NotEmpty(message = "Укажите хотя бы одну цель")
        List<@NotBlank String> goals,

        String wellbeing,

        List<String> restrictions,

        Map<String, Object> extra
) {
}
