-- ===== users =====
CREATE TABLE user_entity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    phone       VARCHAR(255) NOT NULL,
    telegram_id BIGINT,
    name        VARCHAR(255),
    surname     VARCHAR(255),
    gender      VARCHAR(255),
    birthday    DATE,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    CONSTRAINT uq_user_email       UNIQUE (email),
    CONSTRAINT uq_user_phone       UNIQUE (phone),
    CONSTRAINT uq_user_telegram_id UNIQUE (telegram_id),
    CONSTRAINT ck_user_role        CHECK (role IN ('USER', 'SPECIALIST'))
);

-- ===== questionnaire =====
CREATE TABLE questionnaire_entity (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL,
    schema_version INTEGER NOT NULL DEFAULT 1,
    data           JSONB NOT NULL,
    created_at     TIMESTAMP(6),
    updated_at     TIMESTAMP(6),
    CONSTRAINT fk_questionnaire_user
        FOREIGN KEY (user_id) REFERENCES user_entity (id) ON DELETE CASCADE
);
CREATE INDEX idx_questionnaire_user ON questionnaire_entity (user_id, created_at DESC);

-- ===== media =====
CREATE TABLE media_entity (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL,
    type          VARCHAR(255) NOT NULL,
    storage_key   VARCHAR(255) NOT NULL,
    original_name VARCHAR(255),
    content_type  VARCHAR(255) NOT NULL,
    size_bytes    BIGINT NOT NULL,
    created_at    TIMESTAMP(6),
    updated_at    TIMESTAMP(6),
    CONSTRAINT fk_media_user
        FOREIGN KEY (user_id) REFERENCES user_entity (id) ON DELETE CASCADE
);
CREATE INDEX idx_media_user ON media_entity (user_id);

-- ===== exercise library =====
CREATE TABLE exercise (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    description  TEXT,
    muscle_group VARCHAR(255) NOT NULL,
    difficulty   VARCHAR(255),
    video_url    VARCHAR(512),
    created_by   BIGINT,
    active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP(6),
    updated_at   TIMESTAMP(6),
    CONSTRAINT fk_exercise_created_by
        FOREIGN KEY (created_by) REFERENCES user_entity (id) ON DELETE SET NULL,
    CONSTRAINT ck_exercise_difficulty
        CHECK (difficulty IS NULL OR difficulty IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED'))
);
CREATE INDEX idx_exercise_muscle_group ON exercise (muscle_group);

-- ===== program =====
CREATE TABLE program (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL,
    specialist_id      BIGINT NOT NULL,
    title              VARCHAR(255) NOT NULL,
    specialist_comment TEXT,
    priorities         JSONB,
    status             VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at         TIMESTAMP(6),
    updated_at         TIMESTAMP(6),
    CONSTRAINT fk_program_user
        FOREIGN KEY (user_id) REFERENCES user_entity (id) ON DELETE CASCADE,
    CONSTRAINT fk_program_specialist
        FOREIGN KEY (specialist_id) REFERENCES user_entity (id),
    CONSTRAINT ck_program_status
        CHECK (status IN ('ACTIVE', 'COMPLETED', 'ARCHIVED'))
);
CREATE INDEX idx_program_user       ON program (user_id, created_at DESC);
CREATE INDEX idx_program_specialist ON program (specialist_id);

-- ===== program items =====
CREATE TABLE program_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id      BIGINT NOT NULL,
    exercise_id     BIGINT NOT NULL,
    sets            INTEGER,
    reps            INTEGER,
    specialist_note TEXT,
    sort_order      INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6),
    CONSTRAINT fk_program_item_program
        FOREIGN KEY (program_id) REFERENCES program (id) ON DELETE CASCADE,
    CONSTRAINT fk_program_item_exercise
        FOREIGN KEY (exercise_id) REFERENCES exercise (id)
);
CREATE INDEX idx_program_item_program  ON program_item (program_id, sort_order);
CREATE INDEX idx_program_item_exercise ON program_item (exercise_id);

-- ===== completions =====
CREATE TABLE program_completion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_item_id BIGINT NOT NULL,
    user_id         BIGINT NOT NULL,
    feedback        TEXT,
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6),
    CONSTRAINT fk_completion_item
        FOREIGN KEY (program_item_id) REFERENCES program_item (id) ON DELETE CASCADE,
    CONSTRAINT fk_completion_user
        FOREIGN KEY (user_id) REFERENCES user_entity (id) ON DELETE CASCADE
);
CREATE INDEX idx_completion_item ON program_completion (program_item_id, created_at DESC);
CREATE INDEX idx_completion_user ON program_completion (user_id);